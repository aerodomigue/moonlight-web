import assert from 'node:assert/strict';
const { chromium } = await import(process.env.MW_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch();
const base = process.argv[2];
try {
    const context = await browser.newContext({ ignoreHTTPSErrors: true, locale: 'fr-FR', viewport: { width: 1280, height: 900 }, extraHTTPHeaders: { 'X-Forwarded-For': '203.0.113.20', 'X-Forwarded-Proto': 'https' } });
    const page = await context.newPage();
    page.setDefaultTimeout(15000);
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(base, { waitUntil: 'networkidle' });
    await page.locator('#btn-login-sso').click();
    await page.locator('#view-hosts').waitFor();
    await page.locator('#btn-admin').click();
    await page.locator('#admin-oidc-secret').fill('unsaved-browser-fixture');
    await page.locator('#view-admin-tab-network').click();
    await page.locator('#admin-https-port').waitFor();
    await page.locator('#view-admin-tab-login').click();
    assert.equal(await page.locator('#admin-oidc-secret').inputValue(), 'unsaved-browser-fixture');
    await page.locator('#admin-oidc-secret').fill('');
    assert.equal(await page.locator('[role="tab"]').count(), 6);
    await page.locator('#view-admin-tab-users').click();
    await page.locator('#admin-new-user').fill('Test utilisateur');
    await page.locator('#admin-create-user button').click();
    await page.waitForFunction(() => document.querySelector('#admin-user-name')?.value === 'Test utilisateur');
    await page.locator('#admin-user-search').fill('Test utilisateur');
    assert.equal(await page.locator('[data-user-id]:visible').count(), 1);
    await page.locator('[data-user-action="hosts"]').click();
    await page.locator('[data-host-owner]').waitFor();
    await page.waitForFunction(() => !!document.querySelector('[data-host-owner]')?.value);
    assert.equal(await page.locator('#view-admin-tab-hosts').getAttribute('aria-selected'), 'true');
    // Inject only the list response to inspect a populated card; mutations still
    // go through the real signed API and remain covered by the backend fixture.
    await page.route('**/api/admin/hosts', route => route.fulfill({ json: { hosts: [{ uuid: 'fixture-card', name: '<PC Apollo>', owner_id: 'local-owner', state: 'offline', enabled: false, backendType: 'gamestream', blocked_reason: '', busy: false }] } }));
    await page.locator('[data-host-owner]').selectOption('');
    await page.locator('[data-host-refresh]').click();
    await page.locator('[data-host-row]').waitFor();
    assert.match(await page.locator('[data-host-row]').innerText(), /Hors ligne.*Désactivé/s);
    await page.locator('[data-host-row] summary').click();
    await page.locator('[data-host-action="delete"]').click();
    await page.locator('[role="alertdialog"]').waitFor();
    assert.match(await page.locator('[role="alertdialog"]').innerText(), /<PC Apollo>/);
    await page.locator('[data-answer="no"]').click();
    await page.screenshot({ path: 'work/settings-hosts-fr.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: 'work/settings-hosts-mobile-fr.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.unroute('**/api/admin/hosts');
    // SSO-only hides local actions after the successful admin login validates it.
    await page.locator('#view-admin-tab-login').click();
    await page.locator('#admin-login-mode').selectOption('sso');
    await page.locator('#admin-login-form button[type="submit"]').click();
    await page.waitForFunction(() => document.querySelector('#admin-login-mode')?.value === 'sso' && !document.querySelector('#admin-login-form button[type="submit"]').disabled);
    await page.locator('#view-admin-tab-users').click();
    assert.equal(await page.locator('#admin-create-user').count(), 0);
    assert.equal(await page.locator('[data-user-action="pin"]').count(), 0);
    await page.screenshot({ path: 'work/settings-users-sso-fr.png', fullPage: true });
    await page.locator('#btn-admin-close').click();
    await page.locator('#btn-settings').click();
    await page.locator('#view-settings-tab-controls').click();
    await page.locator('#settings-exclusive-mode').selectOption('both');
    await page.locator('#view-settings-tab-general').click();
    await page.locator('#view-settings-tab-controls').click();
    assert.equal(await page.locator('#settings-exclusive-mode').inputValue(), 'both');
    await page.screenshot({ path: 'work/settings-controls-mobile-fr.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.deepEqual(errors, []);
    console.log('PASS: French desktop/mobile tabs, retained SSO draft, searchable users, owner PC navigation, app confirmation, SSO-only actions and personal capture preferences.');
} finally { await browser.close(); }
